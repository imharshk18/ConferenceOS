import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {convexTest} from 'convex-test';
import schema from '../convex/schema';
import {api,internal} from '../convex/_generated/api';
import {uploadMime} from '../packages/core/uploadMedia';
const modules=import.meta.glob('../convex/**/*.ts');
beforeEach(()=>vi.useFakeTimers());
afterEach(()=>{vi.clearAllTimers();vi.useRealTimers();});
it('normalizes native recorder MIME guesses without accepting invalid media',()=>{
 for(const mime of ['application/octet-stream','video/mp4','audio/x-m4a',''])expect(uploadMime('audio','audio/mp4',mime)).toBe('audio/mp4');
 expect(uploadMime('audio','audio/webm','audio/webm;codecs=opus')).toBe('audio/webm');
 expect(()=>uploadMime('photo','image/png','text/html')).toThrow();
});
it('auto-saves synthetic context once, keeps it private, and retries uploads idempotently',async()=>{
 const t=convexTest(schema,modules),id=await t.run(ctx=>ctx.db.insert('users',{}));
 const a=t.withIdentity({subject:`${id}|demo`});
 await a.mutation(api.demo.useHarsh,{});
 const {connectionId}=await a.mutation(api.demo.connect,{code:'123456'});
 const captureId=await a.mutation(api.captures.create,{kind:'conversation',title:'Synthetic test',notes:'',connectionId,consentConfirmed:true,autoSaveDemo:true});
 const path=`/capture-upload?captureId=${captureId}`,request={method:'POST',headers:{'Content-Type':'audio/mp4','X-Upload-Key':'stable-audio-key'},body:new Uint8Array([1,2,3,4])};
 expect((await a.fetch(path,request)).status).toBe(200);
 expect((await a.fetch(path,request)).status).toBe(200);
 expect((await a.query(api.captures.mine,{}))[0].attachmentCount).toBe(1);
 await a.mutation(api.captures.analyze,{captureId,revision:1});
 const args={captureId,revision:2,transcript:'Synthetic creator conversation',draft:{summary:'Creator collaboration ideas',topicIds:[],networkAreas:['content'],takeaways:[],actions:[]},error:null};
 expect(await t.mutation(internal.captures.finish,args)).toBe(true);
 expect(await t.mutation(internal.captures.finish,args)).toBe(false);
 const capture=(await a.query(api.captures.mine,{}))[0];
 expect(capture.status).toBe('approved');
 const memory=await t.run(ctx=>ctx.db.get(capture.memoryId!));
 expect(memory).toMatchObject({autoSaved:true,approvedBy:[],status:'shared'});
 expect((await a.query(api.social.mine,{}))!.memories).toHaveLength(1);
 expect(await t.query(api.captures.mine,{})).toEqual([]);
 const network=await a.query(api.network.mine,{});
 const input=await t.query(internal.network.input,{userId:id,revision:network!.revision});
 expect(input!.memories[0]).toMatchObject({autoSaved:true,demo:true});
 await a.mutation(api.captures.remove,{captureId});
 expect((await a.query(api.social.mine,{}))!.memories).toEqual([]);
});
